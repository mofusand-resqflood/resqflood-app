# Run it from the ROOT of your Flutter project (the folder that contains pubspec.yaml).
# It never overwrites a file that already exists.
set -e
if [ ! -f pubspec.yaml ]; then echo "Run this in the folder that has pubspec.yaml"; exit 1; fi
make() {
  mkdir -p "$(dirname "$1")"
  if [ ! -e "$1" ]; then
    case "$1" in
      *.json) echo "{}" > "$1" ;;
      *) : > "$1" ;;
    esac
    echo "created  $1"
  else
    echo "exists   $1 (left as it is)"
  fi
}
